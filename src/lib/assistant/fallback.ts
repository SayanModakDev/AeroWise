import {
  AssistantActionSummary,
  AssistantEnvironmentalContext,
} from '@/types/assistant';

export function generateLocalFallbackResponse(
  userQuery: string,
  env: AssistantEnvironmentalContext,
  topActions: AssistantActionSummary[]
): {
  reply: string;
  groundingFacts: string[];
  disclaimer: string;
} {
  const q = userQuery.toLowerCase();
  const pm25Text =
    env.currentPm25 !== null ? `${env.currentPm25} µg/m³` : 'unavailable';
  const actionsList =
    topActions.length > 0
      ? topActions.map((a, i) => `${i + 1}. **${a.title}**: ${a.whatToDo}`).join('\n\n')
      : 'Follow standard low-exposure indoor practices.';

  const groundingFacts = [
    `Modelled PM2.5 in ${env.city}: ${pm25Text}`,
    `Trend projection: ${env.trendDirection}`,
    `Top recommended action: ${topActions[0]?.title || 'Reduce outdoor exposure'}`,
    'WHO 2021 24h health reference guideline: 15 µg/m³',
  ];

  const disclaimer =
    'Response generated by the deterministic AeroWise Air-to-Action Engine (Local Fallback). Modelled values are from atmospheric forecasts (CAMS Global) and not validated government monitoring stations.';

  if (
    q.includes('exercise') ||
    q.includes('jog') ||
    q.includes('run') ||
    q.includes('cycling') ||
    q.includes('workout')
  ) {
    return {
      reply: `For physical exercise in **${env.city}** today (where modelled PM2.5 is currently **${pm25Text}**):

- **Avoid outdoor cardio**: Strenuous aerobic exercise triggers mouth breathing and increases lung ventilation volume by up to 500%, depositing fine particulates deep into alveolar tissue.
- **Indoor alternative**: Substitute with indoor yoga, mobility exercises, or bodyweight strength workouts in an enclosed room.
- **Timing advice**: If outdoor movement is mandatory, schedule it during the midday trough (~12:00–15:30) rather than early morning, when surface temperature inversions trap heavy smog.`,
      groundingFacts,
      disclaimer,
    };
  }

  if (
    q.includes('purifier') ||
    q.includes('filter') ||
    q.includes('without buying') ||
    q.includes('cheap') ||
    q.includes('free')
  ) {
    return {
      reply: `Here are the most practical zero-cost ways to reduce indoor pollution without purchasing an air purifier:

1. **Eliminate burning sources**: Stop using agarbatti (incense sticks), dhoop, and smouldering mosquito coils. A single coil can release particulate matter equivalent to dozens of cigarettes.
2. **Wet-mopping instead of sweeping**: Avoid dry straw brooms (jhadu) which resuspend toxic settled road dust into breathing air. Clean floors with a damp microfiber mop.
3. **Kitchen exhaust discipline**: Run your exhaust fan throughout cooking and for 15 minutes afterward to expel combustion and frying aerosols.
4. **Controlled ventilation**: Keep windows closed during morning/evening traffic peaks. Ventilate briefly (10–15 mins) only around midday if outdoor conditions temporarily ease.`,
      groundingFacts,
      disclaimer,
    };
  }

  if (
    q.includes('child') ||
    q.includes('kid') ||
    q.includes('baby') ||
    q.includes('elderly') ||
    q.includes('asthma') ||
    q.includes('vulnerable')
  ) {
    return {
      reply: `Recommendations for vulnerable family members in **${env.city}** under current modelled PM2.5 levels of **${pm25Text}**:

- **Restrict morning outdoor play**: Children have narrower airways and breathe more air per kilogram of body weight. Keep them indoors during early morning inversion peaks.
- **Idle-Free school pickups**: Encourage parents and van drivers outside school gates to turn off vehicle engines while waiting.
- **Barrier protection**: If transit is unavoidable, fit older children and adults with certified particulate respirators (N95/FFP2).
- **Medical vigilance**: Keep prescribed inhalers and medications readily accessible. If any family member develops shortness of breath, persistent coughing, or chest tightness, seek prompt medical attention.`,
      groundingFacts,
      disclaimer,
    };
  }

  if (
    q.includes('commute') ||
    q.includes('transport') ||
    q.includes('travel') ||
    q.includes('office') ||
    q.includes('metro')
  ) {
    return {
      reply: `Commute recommendations for **${env.city}**:

- **Prefer grade-separated transit**: Whenever accessible, choose underground or elevated electric metro rail over street-level auto or bus commutes to avoid breathing direct exhaust plumes.
- **Two-wheeler protection**: Two-wheeler commuters experience the highest roadside black carbon dose. Always wear a sealed N95 respirator beneath a full-face helmet with the visor lowered.
- **Trip chaining**: If driving a car, combine multiple short errands into one loop to avoid repeated cold engine starts and switch off the ignition at long traffic signals.`,
      groundingFacts,
      disclaimer,
    };
  }

  // General query answer grounding directly in current top actions
  return {
    reply: `Based on current environmental conditions in **${env.city}** (modelled PM2.5: **${pm25Text}**, trend: **${env.trendDirection}**), here are the priority actions recommended by your household plan:

${actionsList}

*Tip: You can customize your household setup in the "My Household" tab to tailor these recommendations to your family's exact routine, fuel type, and budget.*`,
    groundingFacts,
    disclaimer,
  };
}
