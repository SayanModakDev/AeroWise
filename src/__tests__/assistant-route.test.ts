import { describe, it, expect, vi, beforeEach } from 'vitest';
import { POST } from '@/app/api/assistant/route';
import { NextRequest } from 'next/server';

// Mock callGeminiAssistant directly to test the route behavior
vi.mock('@/lib/assistant/gemini', () => ({
  callGeminiAssistant: vi.fn(),
}));

import { callGeminiAssistant } from '@/lib/assistant/gemini';

describe('POST /api/assistant Route Handler', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('rejects empty message with status 400', async () => {
    const req = new NextRequest('http://localhost:3000/api/assistant', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: '',
        environmentalContext: {
          city: 'Delhi',
          country: 'India',
        },
      }),
    });

    const res = await POST(req);
    expect(res.status).toBe(400);
    const body = await res.json();
    expect(body.error).toBe('Invalid request structure');
  });

  it('rejects overly long message exceeding 600 characters with status 400', async () => {
    const req = new NextRequest('http://localhost:3000/api/assistant', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: 'A'.repeat(601),
        environmentalContext: {
          city: 'Delhi',
          country: 'India',
        },
      }),
    });

    const res = await POST(req);
    expect(res.status).toBe(400);
  });

  it('successfully returns gemini response with source: "gemini" when Gemini succeeds', async () => {
    (callGeminiAssistant as unknown as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      reply: 'Detailed answer generated by Google Gemini model.',
      groundingFacts: ['Location: New Delhi, India', 'Modelled PM2.5: 180 µg/m³'],
    });

    const req = new NextRequest('http://localhost:3000/api/assistant', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: 'What should I do about outdoor exercise today?',
        environmentalContext: {
          city: 'New Delhi',
          country: 'India',
          currentPm25: 180,
          currentPm10: 270,
          trendDirection: 'rising',
          whoPm25Ratio: 12.0,
        },
        topActions: [
          {
            title: 'Shift Outdoor Errands to Lower-Pollution Afternoon Hours',
            category: 'protect_household',
            whatToDo: 'Postpone outdoor tasks away from morning rush.',
          },
        ],
      }),
    });

    const res = await POST(req);
    expect(res.status).toBe(200);

    const body = await res.json();
    expect(body.source).toBe('gemini');
    expect(body.reply).toBe('Detailed answer generated by Google Gemini model.');
    expect(body.disclaimer).toContain('Generated by Google Gemini AI');
    expect(body.groundingFacts.length).toBe(2);
  });

  it('activates deterministic local engine fallback when Gemini call returns null', async () => {
    // Simulate Gemini unavailable (returns null)
    (callGeminiAssistant as unknown as ReturnType<typeof vi.fn>).mockResolvedValueOnce(null);

    const req = new NextRequest('http://localhost:3000/api/assistant', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: 'What should I do about outdoor exercise today?',
        environmentalContext: {
          city: 'New Delhi',
          country: 'India',
          currentPm25: 180,
          currentPm10: 270,
          trendDirection: 'rising',
          whoPm25Ratio: 12.0,
        },
        topActions: [
          {
            title: 'Shift Outdoor Errands to Lower-Pollution Afternoon Hours',
            category: 'protect_household',
            whatToDo: 'Postpone outdoor tasks away from morning rush.',
          },
        ],
      }),
    });

    const res = await POST(req);
    expect(res.status).toBe(200);

    const body = await res.json();
    expect(body.source).toBe('local_engine');
    expect(body.reply).toContain('New Delhi');
    expect(body.disclaimer).toContain('AeroWise Air-to-Action Engine (Local Fallback)');
  });
});
