import { NextRequest, NextResponse } from 'next/server';
import { z } from 'zod';
import { callGeminiAssistant } from '@/lib/assistant/gemini';
import { generateLocalFallbackResponse } from '@/lib/assistant/fallback';
import { AssistantApiResponse } from '@/types/assistant';

// Schema validation
const requestSchema = z.object({
  message: z.string().trim().min(1, 'Message cannot be empty').max(600, 'Message too long'),
  environmentalContext: z.object({
    city: z.string().default('Selected City'),
    country: z.string().default('Selected Country'),
    currentPm25: z.number().nullable().optional().default(null),
    currentPm10: z.number().nullable().optional().default(null),
    trendDirection: z.string().default('stable'),
    whoPm25Ratio: z.number().nullable().optional().default(null),
  }),
  topActions: z
    .array(
      z.object({
        title: z.string(),
        category: z.string(),
        whatToDo: z.string(),
      })
    )
    .max(10)
    .default([]),
  history: z
    .array(
      z.object({
        role: z.enum(['user', 'assistant']),
        content: z.string().max(1000),
      })
    )
    .optional(),
});

export async function POST(req: NextRequest) {
  try {
    const rawBody = await req.json();
    const parseResult = requestSchema.safeParse(rawBody);

    if (!parseResult.success) {
      return NextResponse.json(
        {
          error: 'Invalid request structure',
          details: parseResult.error.flatten(),
        },
        { status: 400 }
      );
    }

    const { message, environmentalContext, topActions, history } = parseResult.data;

    // Attempt Gemini call
    const geminiResult = await callGeminiAssistant({
      message,
      environmentalContext,
      topActions,
      history,
    });

    if (geminiResult) {
      const response: AssistantApiResponse = {
        reply: geminiResult.reply,
        source: 'gemini',
        groundingFacts: geminiResult.groundingFacts,
        disclaimer:
          'Generated by Google Gemini AI, strictly grounded in AeroWise decision-engine facts. Not medical advice. Modelled values are from atmospheric forecasts, not official monitoring stations.',
      };
      return NextResponse.json(response);
    }

    // Fallback to deterministic local engine
    const fallbackResult = generateLocalFallbackResponse(
      message,
      environmentalContext,
      topActions
    );

    const response: AssistantApiResponse = {
      reply: fallbackResult.reply,
      source: 'local_engine',
      groundingFacts: fallbackResult.groundingFacts,
      disclaimer: fallbackResult.disclaimer,
    };

    return NextResponse.json(response);
  } catch (err: unknown) {
    console.error('Error processing assistant query:', err);
    return NextResponse.json(
      {
        error: 'Internal assistant error',
        message: err instanceof Error ? err.message : 'Unknown error',
      },
      { status: 500 }
    );
  }
}
